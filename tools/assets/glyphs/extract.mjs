// Extracts the outlines of 二 and 人 from Noto Sans JP and writes everything the site derives
// from them: the outline data for the sculpture, the header mark, and the favicon.
// The font is only needed to run this script. Nothing loads it at build time or at runtime.
// Usage: node tools/assets/glyphs/extract.mjs [weight]
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';

const WEIGHT = Number(process.argv[2] ?? 900);
const PACKAGE = '@fontsource/noto-sans-jp';
const dir = `node_modules/${PACKAGE}/files`;
const version = JSON.parse(fs.readFileSync(`node_modules/${PACKAGE}/package.json`, 'utf8')).version;
const CHARS = { ni: '二', hito: '人' };
/** Space between the two characters, in em. Wider than the font's own spacing: the visitor passes through it. */
export const GAP = 0.3;

function find(char) {
	for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(`-${WEIGHT}-normal.woff`))) {
		const buffer = fs.readFileSync(path.join(dir, file));
		const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
		const glyph = font.charToGlyph(char);
		if (glyph && glyph.index > 0 && glyph.path.commands.length > 0) return { font, glyph, file };
	}
	throw new Error(`No ${WEIGHT} subset of ${PACKAGE} contains ${char}`);
}

const r = (v) => Math.round(v * 10000) / 10000;
const glyphs = {};
let family = '';
for (const [key, char] of Object.entries(CHARS)) {
	const { font, glyph, file } = find(char);
	family = font.names.fontFamily?.en ?? 'Noto Sans JP';
	const em = font.unitsPerEm;
	const commands = glyph.path.commands.map((c) => {
		const out = { t: c.type };
		for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) if (c[k] !== undefined) out[k] = r(c[k] / em);
		return out;
	});
	const b = glyph.getBoundingBox();
	glyphs[key] = { char, codepoint: `U+${char.codePointAt(0).toString(16).toUpperCase()}`, file, box: [r(b.x1 / em), r(b.y1 / em), r(b.x2 / em), r(b.y2 / em)], commands };
}

// lay the pair out around x = 0 with the gap between their ink, feet on y = 0
const bottom = Math.min(glyphs.ni.box[1], glyphs.hito.box[1]);
glyphs.ni.offset = [r(-GAP / 2 - glyphs.ni.box[2]), r(-bottom)];
glyphs.hito.offset = [r(GAP / 2 - glyphs.hito.box[0]), r(-bottom)];
const data = {
	source: { family, weight: WEIGHT, package: PACKAGE, version, license: 'OFL-1.1', copyright: 'Copyright 2014-2021 Adobe (http://www.adobe.com/), with Reserved Font Name Source' },
	gap: GAP,
	glyphs,
};
fs.writeFileSync('tools/assets/glyphs/futari-glyphs.json', `${JSON.stringify(data, null, '\t')}\n`);

// vector marks: y flipped for SVG, curves kept exact
function d(key, scale, ox, oy) {
	const g = glyphs[key];
	const px = (x) => r((x + g.offset[0]) * scale + ox);
	const py = (y) => r(oy - (y + g.offset[1]) * scale);
	return g.commands.map((c) => (c.t === 'M' || c.t === 'L' ? `${c.t}${px(c.x)} ${py(c.y)}` : c.t === 'Q' ? `Q${px(c.x1)} ${py(c.y1)} ${px(c.x)} ${py(c.y)}` : c.t === 'C' ? `C${px(c.x1)} ${py(c.y1)} ${px(c.x2)} ${py(c.y2)} ${px(c.x)} ${py(c.y)}` : 'Z')).join('');
}
const left = glyphs.ni.box[0] + glyphs.ni.offset[0];
const right = glyphs.hito.box[2] + glyphs.hito.offset[0];
const top = Math.max(glyphs.ni.box[3], glyphs.hito.box[3]) - bottom;
const W = 100;
const scale = W / (right - left);
const H = r(top * scale);
const pathD = `${d('ni', scale, -left * scale, H)}${d('hito', scale, -left * scale, H)}`;
fs.writeFileSync(
	'src/content/mark.ts',
	`// Generated by tools/assets/glyphs/extract.mjs from ${family} ${WEIGHT} (OFL-1.1). Do not edit.\nexport const mark = {\n\tviewBox: '0 0 ${W} ${H}',\n\tpath: '${pathD}',\n} as const;\n`,
);
const pad = 14;
fs.writeFileSync(
	'public/favicon.svg',
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-pad} ${r(-(W + 2 * pad - H) / 2)} ${W + 2 * pad} ${W + 2 * pad}"><rect x="${-pad}" y="${r(-(W + 2 * pad - H) / 2)}" width="${W + 2 * pad}" height="${W + 2 * pad}" rx="18" fill="#1b2230"/><path fill="#f4f7fb" d="${pathD}"/></svg>\n`,
);
console.log(JSON.stringify({ family, weight: WEIGHT, version, files: [glyphs.ni.file, glyphs.hito.file], boxes: { ni: glyphs.ni.box, hito: glyphs.hito.box }, commands: { ni: glyphs.ni.commands.length, hito: glyphs.hito.commands.length }, mark: `0 0 ${W} ${H}` }));
